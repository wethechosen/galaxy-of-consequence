import { expect, it, vi, beforeEach } from "vitest";
vi.mock("@/lib/accounts",()=>({requireAccount:vi.fn()}));
vi.mock("@/lib/local-http",()=>({assertLocalRequest:vi.fn()}));
import {requireAccount} from "@/lib/accounts";
import {GET} from "@/app/api/npcs/route";
const request=()=>new Request("http://localhost/api/npcs");
beforeEach(()=>vi.resetAllMocks());
it("denies the private GM NPC registry to ordinary players and signed-out users",async()=>{
  vi.mocked(requireAccount).mockImplementation(()=>{throw Error("Administrator access required.");});
  const response=await GET(request());
  expect(response.status).toBe(403);
  expect(JSON.stringify(await response.json())).not.toContain("Kelvek");
});
it("preserves audited NPC progress with one GM dossier per character",async()=>{
  vi.mocked(requireAccount).mockReturnValue({id:"gm-1",username:"gm",displayName:"GM",role:"admin"});
  const response=await GET(request());
  expect(response.status).toBe(200);
  expect(vi.mocked(requireAccount)).toHaveBeenCalledWith(expect.any(Request),true);
  const result=await response.json();
  expect(result.roster).toHaveLength(47);
  expect(result.canonicalRegistry).toHaveLength(54);
  for(const npc of result.canonicalRegistry){
    expect(npc.definitiveDossier?.id,npc.id).toBe(npc.id);
    expect(npc.design.level,npc.id).toBe(npc.definitiveDossier.combat.level);
    expect(npc.design.priorCareerXp,npc.id).toBe(npc.definitiveDossier.combat.careerXp);
    expect(npc.definitiveDossier.combat.level,npc.id).toBeGreaterThan(0);
    expect(npc.definitiveDossier.combat.feats.length,npc.id).toBeGreaterThan(0);
    expect(npc.definitiveDossier.equipment.neverGrantAutomatically,npc.id).toBe(true);
  }
  expect(result.canonicalRegistrySummary).toMatchObject({core:25,personal:13,simulations:9,relatives:2,pendingSourcebook:5});
  expect(new Set(result.canonicalRegistry.map((x:{id:string})=>x.id)).size).toBe(54);
  expect(result.canonicalRegistry.filter((x:{name:string})=>x.name==="Darth Korvalis")).toHaveLength(1);
  const royal=result.canonicalRegistry.find((x:{id:string})=>x.id==="seralyth-vhaelor");
  expect(royal.mechanics.status).toBe("authored-saga-sheet");
  expect(royal.design.level).toBe(8);
  expect(result.canonicalRegistry.find((x:{id:string})=>x.id==="maera-holloran").worldState).toBe("historical-only");
  expect(result.felLegendsBaseline.knightDoctrine).toMatch(/dark side/);
  expect(new Set(result.roster.map((entry:{id:string})=>entry.id)).size).toBe(47);
  expect(new Set(result.roster.map((entry:{name:string})=>entry.name.toLowerCase())).size).toBe(result.roster.length);
  const scenarios=result.roster.filter((n:{category:string})=>n.category==="test");
  expect(scenarios).toHaveLength(10);
  expect(scenarios.some((n:{id:string})=>n.id==="kelvek"||n.id==="dmir-holloran")).toBe(false);
  expect(scenarios.some((n:{id:string})=>n.id==="calen-vardex")).toBe(true);
  expect(result.endingCountVerified).toBe(1);
  expect(result.endingEvidenceScope).toBe("audited-isolated-live-playthroughs-not-hosted-saves");
  const bren=result.roster.find((entry:{id:string})=>entry.id==="bren-varo");
  expect(bren.playthroughStatus).toBe("goal_complete");
  expect(bren.auditedEnding.evidenceTurnIds).toHaveLength(5);
  expect(bren.auditedEnding.hostedSaveMigrated).toBe(false);
  expect(bren.visualReference).toMatch(/desert guide/i);
  expect(result.visibility).toBe("gm-only");
  const seralyth=result.roster.find((n:{id:string})=>n.id==="story-seralyth-vhaelor");
  expect(seralyth).toBeDefined();
  expect(seralyth.sagaSheet.controller).toBe("ai-gm");
  expect(seralyth.sagaSheet.talents.map((n:{name:string})=>n.name)).toContain("Block");
  expect(seralyth.initialScene.status).toBe("prepared-not-played");
  expect(seralyth.gmDossier.prisonGangConnection.kelvekTruth).toMatch(/skimmed/);
  expect(result.roster.some((n:{category:string;secret?:string})=>n.category==="story"&&n.secret)).toBe(true);
  for(const entry of result.roster)expect(entry.playthroughStatus).toBe(entry.id==="bren-varo"?"goal_complete":"unverified");
  expect(result.roster.filter((entry:{name:string})=>entry.name==="Kelvek")).toHaveLength(1);
  expect(result.roster.find((entry:{id:string})=>entry.id==="story-kelvek").era).toBe(147);
  expect(result.roster.find((entry:{id:string})=>entry.id==="story-kelvek").description).toMatch(/STAFF LIBRARIAN/);
  expect(result.roster.filter((entry:{name:string})=>entry.name==="Darth Korvalis")).toHaveLength(1);
  expect(result.roster.some((entry:{id:string})=>entry.id==="story-korvalis")).toBe(true);
  expect(result.roster.find((entry:{id:string})=>entry.id==="aliyah-fel").designation).not.toMatch(/empress/i);
});
